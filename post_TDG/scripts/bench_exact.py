"""Benchmark exact solvers (MILP/HiGHS vs CP-SAT) on synthetic random DAGs; writes docs/benchmarks/exact_scaling.md.

Instances are SYNTHETIC (datagen.random_dag); numbers measure solver behaviour, not hardware.

Usage: python scripts/bench_exact.py [--sizes 10 20 30 40 60] [--time-limit 30] [--seeds 0]
"""

from __future__ import annotations

import argparse
import platform as pyplatform
from datetime import date
from pathlib import Path

from datagen import random_dag
from estimate import annotate
from schemas import load_platform
from schemas.platform import Platform
from sim import evaluate
from solvers.cp import solve_cp
from solvers.heuristics import heft
from solvers.ilp import solve_ilp

ROOT = Path(__file__).resolve().parents[1]


def two_cpu_platform() -> Platform:
    base = load_platform(ROOT / "platforms" / "toy_cpu_fpga.synthetic.json").model_dump(mode="json")
    base["id"] = "toy_2cpu_fpga"
    base["pes"].insert(1, {**base["pes"][0], "id": "cpu1"})
    base["interfaces"][0]["connects"] = ["cpu0", "cpu1", "fpga0"]
    return Platform.model_validate(base)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[10, 20, 30, 40, 60])
    ap.add_argument("--time-limit", type=float, default=30.0)
    ap.add_argument("--seeds", type=int, nargs="+", default=[0])
    args = ap.parse_args()

    platforms = {"1 CPU + FPGA": load_platform(ROOT / "platforms" / "toy_cpu_fpga.synthetic.json"),
                 "2 CPUs + FPGA": two_cpu_platform()}
    rows = []
    for pname, plat in platforms.items():
        for n in args.sizes:
            for seed in args.seeds:
                g = random_dag(n, seed, platform_id=plat.id)
                p = annotate(g, plat)
                h = heft(p, insertion=False)
                h_ms = evaluate(p, h.mapping, priority=h.priority, contention=False).sim.makespan
                il = solve_ilp(p, time_limit_s=args.time_limit)
                cp = solve_cp(p, time_limit_s=args.time_limit, hint=h.mapping)
                rows.append((pname, n, seed, h_ms, il, cp))
                print(f"{pname:14s} n={n:3d} seed={seed} HEFT={h_ms:8.2f} | ILP {il.status:10s} {il.runtime_s:6.1f}s "
                      f"C={il.makespan} | CP {cp.status:10s} {cp.runtime_s:6.1f}s C={cp.makespan} gap={cp.gap}",
                      flush=True)

    def fmt(x: float | None, d: int = 2) -> str:
        return "—" if x is None else f"{x:.{d}f}"

    lines = [
        "# Exact solver scaling: MILP (HiGHS) vs CP-SAT",
        "",
        f"Generated by `scripts/bench_exact.py` on {date.today().isoformat()} ({pyplatform.processor() or 'CPU'}; "
        f"time limit {args.time_limit:g} s per solve; CP-SAT 8 workers, warm-started from HEFT).",
        "**Instances are synthetic** (`datagen.random_dag`, uniform costs). Both models are exact for the "
        "no-contention semantics; makespans are in the model's own time unit (ms).",
        "",
        "| platform | tasks | seed | HEFT makespan | MILP status | MILP time (s) | MILP makespan | "
        "CP-SAT status | CP-SAT time (s) | CP-SAT makespan | CP-SAT gap |",
        "|---|---:|---:|---:|---|---:|---:|---|---:|---:|---:|",
    ]
    for pname, n, seed, h_ms, il, cp in rows:
        gap = "—" if cp.gap is None else f"{100 * cp.gap:.1f}%"
        lines.append(f"| {pname} | {n} | {seed} | {fmt(h_ms)} | {il.status} | {fmt(il.runtime_s, 1)} | "
                     f"{fmt(il.makespan)} | {cp.status} | {fmt(cp.runtime_s, 1)} | {fmt(cp.makespan)} | {gap} |")
    out = ROOT / "docs" / "benchmarks" / "exact_scaling.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
