"""Run `solve_exact` on the open instances of the 60–100-task set, warm-started with the best known schedule, and
merge the results into data/benchmarks/large_best_known.synthetic.json (better schedule / stronger bound wins).

Writes docs/benchmarks/exact_large_closing.md (before / after per instance). SYNTHETIC instances.
Usage: python scripts/close_large_gaps.py [--budget 60] [--seeds ...]
"""

from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from estimate import annotate
from estimate.annotate import Option
from schemas.ir import TaskGraph
from schemas.platform import Platform
from solvers.exact import solve_exact
from solvers.heuristics.list_sched import Plan

ROOT = Path(__file__).resolve().parents[1]
LABELS = ROOT / "data" / "labels" / "tier_a_v0_bus_large.synthetic.jsonl"
BEST = ROOT / "data" / "benchmarks" / "large_best_known.synthetic.json"
OUT = ROOT / "docs" / "benchmarks" / "exact_large_closing.md"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--budget", type=float, default=60.0)
    ap.add_argument("--seeds", type=int, nargs="*", default=None)
    args = ap.parse_args()
    best = json.loads(BEST.read_text(encoding="utf-8"))
    recs = {json.loads(x)["seed"]: json.loads(x) for x in LABELS.read_text(encoding="utf-8").splitlines()}
    open_seeds = args.seeds or sorted(int(s) for s, e in best["instances"].items()
                                      if not e["optimal"] and not e["infeasible"])
    rows = []
    for seed in open_seeds:
        e = best["instances"][str(seed)]
        r = recs[seed]
        p = annotate(TaskGraph.model_validate(r["graph"]), Platform.model_validate(r["platform"]))
        warm = []
        if e.get("mapping"):
            warm.append(Plan({t: Option(*v) for t, v in e["mapping"].items()}, e.get("priority")))
        res = solve_exact(p, time_limit_s=args.budget, warm_starts=warm)
        before = (e["best_makespan_ms"], e["bound_ms"], e["gap"])
        ub = min(x for x in (e["best_makespan_ms"], res.makespan_ms) if x is not None) \
            if (e["best_makespan_ms"] or res.makespan_ms) else None
        lb = max(x for x in (e["bound_ms"], res.bound_ms) if x is not None) \
            if (e["bound_ms"] is not None or res.bound_ms is not None) else None
        if lb is not None and ub is not None:
            if lb > ub * (1 + 1e-3):
                raise RuntimeError(f"seed {seed}: bound {lb} above schedule {ub}")
            lb = min(lb, ub)
        if res.status == "infeasible":
            e.update(infeasible=True, certificate=res.certificate)
        if res.makespan_ms is not None and (e["best_makespan_ms"] is None or res.makespan_ms < e["best_makespan_ms"]):
            e.update(best_makespan_ms=res.makespan_ms, best_source=f"solve_exact ({res.method})",
                     mapping={t: [o.pe, o.impl] for t, o in res.plan.mapping.items()}, priority=res.plan.priority)
        gap = None if ub is None or lb is None or ub <= 0 else max(0.0, (ub - lb) / ub)
        e.update(bound_ms=lb, gap=gap, optimal=gap is not None and gap <= 1e-3)
        rows.append((seed, len(p.order), before, (ub, lb, gap), res))
        print(seed, res.status, res.method, res.makespan_ms, res.bound_ms, f"{res.runtime_s:.0f}s", flush=True)
    best["provenance"]["source"] += f"; closed with scripts/close_large_gaps.py (solve_exact, {args.budget:g} s)"
    BEST.write_text(json.dumps(best, indent=1), encoding="utf-8")

    def f(x, fmt):
        return "—" if x is None else format(x, fmt)

    lines = [
        "# Closing the open 60–100-task instances with `solve_exact`",
        "",
        f"Generated by `scripts/close_large_gaps.py` on {date.today().isoformat()}: `solve_exact` with "
        f"**{args.budget:g} s** per instance, warm-started with the best known schedule (from "
        "`exact_large.md`). Before = best known after the 20 s comparison; after = merged (better schedule, "
        "stronger trusted bound). Gap = (schedule − bound) / schedule. **Synthetic instances.**",
        "",
        "| seed | tasks | before: best | bound | gap | after: best | bound | gap | status | method | certificate |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---|---|---|",
    ]
    for seed, n, (b_ub, b_lb, b_g), (ub, lb, g), res in rows:
        lines.append(f"| {seed} | {n} | {f(b_ub, '.2f')} | {f(b_lb, '.2f')} | {f(b_g, '.1%')} | {f(ub, '.2f')} | "
                     f"{f(lb, '.2f')} | {f(g, '.1%')} | {res.status} | {res.method or '—'} | "
                     f"{'; '.join(res.certificate)} |")
    n_opt = sum(1 for e in best["instances"].values() if e["optimal"])
    n_inf = sum(1 for e in best["instances"].values() if e["infeasible"])
    lines += ["", f"Best known now: **{n_opt}** of {len(best['instances'])} optimal within 0.1%, {n_inf} proven "
              "infeasible."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[-3:]))


if __name__ == "__main__":
    main()
