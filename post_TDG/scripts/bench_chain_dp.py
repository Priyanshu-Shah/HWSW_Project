"""CP-SAT vs the exact chain DP on long chains: how far is CP-SAT from the true optimum as size grows?

Chains with 1–4 implementations per task (CPU + up to 3 FPGA variants) and one LUT budget on the toy CPU+FPGA
platform; the DP (`solvers/exact/chain_dp.py`) is exact for this case. SYNTHETIC instances (same generator as
tests/test_chain_dp.py). Writes docs/benchmarks/chain_dp_vs_cpsat.md.

Usage: python scripts/bench_chain_dp.py [--sizes 50 100 200 500 1000] [--budget 30]
"""

from __future__ import annotations

import argparse
import platform as host
import time
from datetime import date
from pathlib import Path

import numpy as np

from estimate import annotate
from schemas import load_platform
from schemas.ir import TaskGraph
from schemas.platform import Platform
from sim import evaluate
from solvers.cp import solve_cp
from solvers.exact.chain_dp import chain_dp
from solvers.exact.relaxation import relaxation_bound
from solvers.heuristics.list_sched import heft

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "benchmarks" / "chain_dp_vs_cpsat.md"


def chain(n: int, seed: int, cap_per_task: float = 20.0):
    rng = np.random.default_rng(seed)
    nodes = []
    for i in range(n):
        sw = float(rng.integers(5, 50))
        impls = [{"id": "sw", "pe_type": "cpu.generic", "cost": {"time_ms": sw}}]
        for k in range(int(rng.integers(0, 4))):
            impls.append({"id": f"hw{k}", "pe_type": "fpga.generic",
                          "cost": {"time_ms": float(rng.integers(1, int(sw))),
                                   "resources": {"LUT": int(rng.integers(20, 300))}}})
        nodes.append({"id": f"t{i}", "implementations": impls})
    edges = [{"src": f"t{i}", "dst": f"t{i + 1}", "bytes": int(rng.integers(100, 5000))} for i in range(n - 1)]
    g = TaskGraph.model_validate({"id": f"chain{n}_{seed}", "provenance": {"kind": "synthetic", "source": "bench"},
                                  "platform": {"id": "toy_cpu_fpga"}, "nodes": nodes, "edges": edges})
    plat = load_platform(ROOT / "platforms" / "toy_cpu_fpga.synthetic.json").model_dump(mode="json")
    plat["pes"][1]["capacity"] = {"LUT": int(cap_per_task * n)}  # budget scales with the chain: stays binding
    return annotate(g, Platform.model_validate(plat))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[50, 100, 200, 500, 1000])
    ap.add_argument("--budget", type=float, default=30.0)
    args = ap.parse_args()
    lines = [
        "# CP-SAT vs the exact chain DP on long chains",
        "",
        f"Generated by `scripts/bench_chain_dp.py` on {date.today().isoformat()} ({host.processor() or host.machine()}). "
        f"**Synthetic chains** (1 CPU + 1 FPGA, 1–4 implementations per task, LUT budget = 20 × tasks, so it binds). "
        f"The DP is exact on chains (contention cannot change a chain's makespan). CP-SAT: {args.budget:g} s, "
        "8 workers, HEFT warm start, bus contention on. The mapping relaxation is exact on chains (no ordering "
        "freedom to drop); it matches the DP within HiGHS's 0.01% MIP gap tolerance.",
        "",
        "| tasks | DP optimum | DP time (s) | HEFT / optimum | CP-SAT status | CP-SAT / optimum | CP-SAT bound / optimum "
        "| relaxation bound / optimum | relaxation time (s) |",
        "|---:|---:|---:|---:|---|---:|---:|---:|---:|",
    ]
    for n in args.sizes:
        p = chain(n, seed=n)
        t0 = time.perf_counter()
        m, opt = chain_dp(p)
        dp_t = time.perf_counter() - t0
        assert evaluate(p, m).feasible
        h = heft(p)
        h_ms = evaluate(p, h.mapping, priority=h.priority, insertion=True).sim.makespan
        c = solve_cp(p, time_limit_s=args.budget, workers=8, seed=0, hint=h.mapping, contention=True)
        cms = evaluate(p, c.mapping).sim.makespan if c.mapping else None
        cb = c.bound * p.norms["latency"] if c.bound is not None else None
        t1 = time.perf_counter()
        rb = relaxation_bound(p, time_limit_s=args.budget)
        rel = f"{rb.bound_ms / opt:.5f} | {time.perf_counter() - t1:.1f}"
        lines.append(f"| {n} | {opt:.1f} | {dp_t:.2f} | {h_ms / opt:.3f} | {c.status} | "
                     f"{cms / opt:.3f} | {cb / opt:.3f} | {rel} |" if cms else
                     f"| {n} | {opt:.1f} | {dp_t:.2f} | {h_ms / opt:.3f} | {c.status} | — | — | {rel} |")
        print(lines[-1], flush=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
