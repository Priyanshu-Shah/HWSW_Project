"""Scaling of the exact solvers on Tier A instances: size x FPGA pressure x bus contention.

For each instance (SYNTHETIC, Tier A v0 generator; deadline = all-SW makespan, so every instance is feasible):
  - mapping relaxation (lower bound, `solvers/exact/relaxation.py`);
  - CP-SAT with bus contention (HEFT warm start);
  - CP-SAT without contention;
  - MILP (HiGHS) without contention, only up to --milp-max tasks (it stops proving optimality beyond ~20 tasks).
Raw results are appended to data/benchmarks/exact_scaling_runs.synthetic.jsonl (resumable). Writes
docs/benchmarks/exact_scaling_tier_a.md.

Usage: python scripts/bench_exact_scaling.py [--sizes 10 20 30 40 50 60] [--seeds 3] [--budget 20] [--milp-max 30]
"""

from __future__ import annotations

import argparse
import json
import platform as host
import statistics
import time
from datetime import date
from pathlib import Path

from datagen.tier_a import TierAConfig, generate
from estimate import annotate
from solvers.cp import solve_cp
from solvers.exact.relaxation import relaxation_bound
from solvers.heuristics.list_sched import heft
from solvers.ilp import solve_ilp

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "data" / "benchmarks" / "exact_scaling_runs.synthetic.jsonl"
OUT = ROOT / "docs" / "benchmarks" / "exact_scaling_tier_a.md"
PRESSURE = {"loose": (0.5, 0.8), "tight": (1.5, 2.0)}  # FPGA demand of the HW-capable tasks / capacity
SEED0 = 7000


def instance(n: int, pressure: str, k: int):
    cfg = TierAConfig(n_tasks=(n, n), fpga_pressure=PRESSURE[pressure], deadline_tightness=(1.0, 1.0))
    seed = SEED0 + 1000 * list(PRESSURE).index(pressure) + 10 * n + k
    g, p = generate(seed, cfg)
    return seed, annotate(g, p)


def run(prob, method: str, budget: float) -> dict:
    t0 = time.perf_counter()
    if method == "relax":
        r = relaxation_bound(prob, time_limit_s=budget)
        return {"status": r.status, "makespan": None, "bound": r.bound_ms, "runtime_s": time.perf_counter() - t0}
    if method == "milp":
        r = solve_ilp(prob, time_limit_s=budget, relax_if_infeasible=False)
        return {"status": r.status, "makespan": r.makespan, "bound": None, "runtime_s": time.perf_counter() - t0}
    c = solve_cp(prob, time_limit_s=budget, workers=8, seed=0, hint=heft(prob).mapping,
                 contention=method == "cpsat_bus")
    return {"status": c.status, "makespan": c.makespan,
            "bound": c.bound * prob.norms["latency"] if c.bound is not None else None,
            "runtime_s": time.perf_counter() - t0}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", type=int, nargs="+", default=[10, 20, 30, 40, 50, 60])
    ap.add_argument("--seeds", type=int, default=3)
    ap.add_argument("--budget", type=float, default=20.0)
    ap.add_argument("--milp-max", type=int, default=30)
    args = ap.parse_args()
    done = set()
    if RUNS.exists():
        for line in RUNS.read_text(encoding="utf-8").splitlines():
            d = json.loads(line)
            if d["budget_s"] == args.budget:
                done.add((d["seed"], d["method"]))
    RUNS.parent.mkdir(parents=True, exist_ok=True)
    for n in args.sizes:
        for pressure in PRESSURE:
            for k in range(args.seeds):
                seed, prob = instance(n, pressure, k)
                methods = ["relax", "cpsat_bus", "cpsat_nobus"] + (["milp"] if n <= args.milp_max else [])
                for m in methods:
                    if (seed, m) in done:
                        continue
                    rec = {"seed": seed, "n": n, "pressure": pressure, "method": m, "budget_s": args.budget,
                           **run(prob, m, args.budget)}
                    with RUNS.open("a", encoding="utf-8") as fh:
                        fh.write(json.dumps(rec) + "\n")
                    print(n, pressure, k, m, rec["status"], f"{rec['runtime_s']:.1f}s", flush=True)
    report(args.budget)


def report(budget: float) -> None:
    rows: dict[tuple[int, str], dict[str, list[dict]]] = {}
    by_seed: dict[int, dict[str, dict]] = {}
    for line in RUNS.read_text(encoding="utf-8").splitlines():
        d = json.loads(line)
        if d["budget_s"] != budget:
            continue
        rows.setdefault((d["n"], d["pressure"]), {}).setdefault(d["method"], []).append(d)
        by_seed.setdefault(d["seed"], {})[d["method"]] = d

    def med(xs: list[float]) -> str:
        return f"{statistics.median(xs):.2f}" if xs else "—"

    lines = [
        "# Exact solver scaling on Tier A: size × FPGA pressure × bus contention",
        "",
        f"Generated by `scripts/bench_exact_scaling.py` on {date.today().isoformat()} ({host.processor() or host.machine()}). "
        f"Budget **{budget:g} s** per solve, CP-SAT 8 workers with HEFT warm start, MILP = HiGHS (1 thread, no "
        "contention model). **Synthetic instances** (Tier A v0 generator; deadline = all-SW makespan, so all are "
        "feasible). FPGA pressure = smallest HW footprint of the HW-capable tasks / capacity: loose 0.5–0.8, "
        "tight 1.5–2.0. `opt` = proven optimal within the budget; times are medians over proven instances; the "
        "relaxation column is the median of best CP-SAT makespan (with contention) / mapping-relaxation bound. "
        "`inf.` = reported infeasible: here a CP-SAT µs-rounding artifact (the deadline equals the all-SW makespan "
        "to the ns, which is also the optimum; CP-SAT rounds each duration to whole µs; with +10 µs it is optimal "
        "at that value; DECISIONS 2026-11-06).",
        "",
        "| tasks | FPGA | n | CP-SAT bus: opt | time (s) | CP-SAT no bus: opt | time (s) | MILP no bus: opt | time (s) | "
        "best / relaxation bound | relaxation time (s) |",
        "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for (n, pressure), ms in sorted(rows.items()):
        def opt(m: str) -> tuple[str, str]:
            xs = ms.get(m, [])
            if not xs:
                return "—", "—"
            good = [x for x in xs if x["status"] == "optimal"]
            inf = sum(x["status"] == "infeasible" for x in xs)
            return f"{len(good)}/{len(xs)}" + (f" ({inf} inf.)" if inf else ""), med([x["runtime_s"] for x in good])
        ratios = []
        for x in ms.get("cpsat_bus", []):
            rb = by_seed[x["seed"]].get("relax", {}).get("bound")
            if x["makespan"] and rb:
                ratios.append(x["makespan"] / rb)
        k = len(ms.get("cpsat_bus", []))
        a, b, c = opt("cpsat_bus"), opt("cpsat_nobus"), opt("milp")
        lines.append(f"| {n} | {pressure} | {k} | {a[0]} | {a[1]} | {b[0]} | {b[1]} | {c[0]} | {c[1]} | "
                     f"{med(ratios)} | {med([x['runtime_s'] for x in ms.get('relax', [])])} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
