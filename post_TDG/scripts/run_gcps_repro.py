"""Reproduce Zheng et al. 2021 (GCPS), Case 1: CT2, AP = 1/3, N in {20, 50, 100, 200, 500, 1000}.

Methods, all scored by LSSP: GCPS (our re-implementation), greedy by HW gain per area, KL (Mann-style, LSSP gain,
q = 1.1), SA (Table 3 parameters). KL/SA run under a wall-clock budget. Instances are SYNTHETIC (TGFF 3.5 topology,
Table 2 cost ranges). Writes docs/benchmarks/gcps_reproduction.md.

Usage: python scripts/run_gcps_repro.py [--graphs 5] [--budget 10] [--sizes 20 50 100 200 500 1000]
"""

from __future__ import annotations

import argparse
import statistics
import time
from datetime import date
from pathlib import Path

from solvers.gcps.baselines import greedy_hgp, kl_lssp, sa_lssp
from solvers.gcps.instance import generate
from solvers.gcps.lssp import lssp
from solvers.gcps.model import gcps

ROOT = Path(__file__).resolve().parents[1]
PAPER = {  # Table 4: AR, CT2, AP = 1/3 (GA, HGA, SA, GSA, KL, GCPS)
    20: (1.441, 1.580, 1.444, 1.612, 1.459, 1.635), 50: (1.591, 1.623, 1.525, 1.641, 1.569, 1.723),
    100: (1.590, 1.565, 1.523, 1.646, 1.568, 1.756), 200: (1.575, 1.573, 1.541, 1.635, 1.580, 1.768),
    500: (1.552, 1.546, 1.533, 1.641, 1.601, 1.796), 1000: (1.514, 1.563, 1.548, 1.668, 1.575, 1.835),
}
PAPER_TIME = {20: (0.013, 0.55), 50: (0.04, 0.85), 100: (0.18, 1.0), 200: (1.0, 1.3), 500: (23, 4), 1000: (150, 8)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--graphs", type=int, default=5)
    ap.add_argument("--budget", type=float, default=10.0)
    ap.add_argument("--sizes", type=int, nargs="+", default=[20, 50, 100, 200, 500, 1000])
    args = ap.parse_args()
    rows = []
    for n in args.sizes:
        res: dict[str, list[tuple[float, float]]] = {m: [] for m in ("gcps", "greedy", "kl", "sa")}
        for inst in generate(n, "CT2", 1 / 3, seed=0, graphs=args.graphs):
            r = gcps(inst)
            res["gcps"].append((r.ar, r.runtime_s))
            for name, fn in (("greedy", lambda: greedy_hgp(inst)),
                             ("kl", lambda: kl_lssp(inst, budget_s=args.budget, candidates=None if n <= 100 else 10)),
                             ("sa", lambda: sa_lssp(inst, budget_s=args.budget))):
                t0 = time.perf_counter()
                y = fn()
                res[name].append((inst.t_max / lssp(inst, y), time.perf_counter() - t0))
            print(n, {k: round(v[-1][0], 3) for k, v in res.items()}, flush=True)
        rows.append((n, {k: (statistics.mean(a for a, _ in v), statistics.mean(t for _, t in v)) for k, v in res.items()}))

    lines = [
        "# GCPS reproduction (Zheng et al. 2021, Case 1: CT2, AP = 1/3)",
        "",
        f"Generated by `scripts/run_gcps_repro.py` on {date.today().isoformat()}: {args.graphs} TGFF graphs per size "
        f"(the paper used 10), KL and SA with a {args.budget:g} s budget per graph, GCPS to its own stopping rule. "
        "All methods are scored by our LSSP, which reproduces the paper's Table 1 exactly. **Synthetic instances**; "
        "the paper's TGFF options and seeds are not published, so absolute AR values are not comparable — compare "
        "the *ordering* and the GCPS-vs-greedy margin.",
        "",
        "| N | ours: GCPS | ours: greedy HGP | ours: KL | ours: SA | paper: GCPS | paper: best baseline (GSA) | paper: KL | "
        "ours GCPS time (s) | paper GCPS time (s) |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for n, m in rows:
        p = PAPER.get(n)
        pt = PAPER_TIME.get(n, (float("nan"), float("nan")))
        lines.append(f"| {n} | {m['gcps'][0]:.3f} | {m['greedy'][0]:.3f} | {m['kl'][0]:.3f} | {m['sa'][0]:.3f} | "
                     f"{p[5]:.3f} | {p[3]:.3f} | {p[4]:.3f} | {m['gcps'][1]:.2f} | ~{pt[1]:g} |")
    lines += [
        "",
        "AR = all-SW time / schedule length (higher is better). Wall-clock times are indicative only: other jobs "
        "shared the machine during the 2026-10-22 run, and KL/SA results at N ≥ 200 are limited by the budget "
        "(KL there examines 10 random candidate moves per step).",
        "",
        "## Findings (2026-10-22)",
        "",
        "- **The paper's ordering is not reproduced.** Our GCPS ties greedy-by-HGP from N = 100 upwards (within "
        "0.01 AR) and loses to it at N = 20 and 50. The paper reports GCPS above all baselines at every size.",
        "- **Cause, measured with `scripts/diag_gcps_saturation.py`:** the loss Σ(t_h·x + t_s·(1 − x)) has no area "
        "or communication term, and t_h < t_s for every task, so its minimum is x = 1 everywhere. On one graph per "
        "size the GCN output saturates (N = 1000: 100% of tasks above 0.99 at the last evaluation; N = 100: 90%), and "
        "Kendall τ between the blended score X' = 0.7·X + 0.3·HGP and HGP alone rises to 0.998 (N = 1000) and "
        "0.943 (N = 100). The cut line then picks almost exactly the greedy-HGP set.",
        "- **At N = 20 the paper's stopping rule ends the search early.** k = N/5 = 4 epochs without improvement, "
        "so the run ended after 5 epochs, before X had saturated, with a partition worse than greedy.",
        "- **What this means for us:** with only what the paper publishes, GCPS is a noisy, slower route to the "
        "greedy-HGP result. The reported margin over GSA must come from something unpublished (loss weighting, "
        "feature scaling, or the stopping rule). We keep GCPS as a reference baseline only. Our GNN is trained "
        "by imitation of exact labels instead (`docs/benchmarks/gnn_imitation.md`).",
    ]
    out =ROOT / "docs" / "benchmarks" / "gcps_reproduction.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
