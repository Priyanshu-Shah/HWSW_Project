"""Heuristics vs exact optimum on Tier A instances (full model with bus contention); writes
docs/benchmarks/heuristics_vs_optimum.md.

The optimum is the CP-SAT bus-contention label from data/labels/tier_a_v0_bus.synthetic.jsonl. Each heuristic's
mapping is evaluated by the simulator with its own list order and insertion mode. Instances are SYNTHETIC.

Usage: python scripts/bench_heuristics.py [--n 15] [--heuristics heft peft ...]
"""

from __future__ import annotations

import argparse
import json
import statistics
import time
from datetime import date
from pathlib import Path

from estimate import annotate
from schemas.ir import TaskGraph
from schemas.platform import Platform
from sim import evaluate
from solvers.heuristics import HEURISTICS, plan

ROOT = Path(__file__).resolve().parents[1]
LABELS = ROOT / "data" / "labels" / "tier_a_v0_bus.synthetic.jsonl"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=15)
    ap.add_argument("--heuristics", nargs="+", default=[h for h in HEURISTICS if h not in ("all_sw", "all_hw")])
    args = ap.parse_args()
    recs = [json.loads(line) for line in LABELS.open(encoding="utf-8")]
    recs = [r for r in recs if r["label"]["status"] == "optimal"][: args.n]
    res: dict[str, list[tuple[float, bool, float]]] = {h: [] for h in args.heuristics}
    for r in recs:
        prob = annotate(TaskGraph.model_validate(r["graph"]), Platform.model_validate(r["platform"]))
        opt = r["label"]["makespan_ms"]
        line = [f"{r['id']} n={r['params']['n_tasks']} opt={opt:.3f}"]
        for h in args.heuristics:
            t0 = time.perf_counter()
            pl = plan(prob, h, 0)
            dt = time.perf_counter() - t0
            ev = evaluate(prob, pl.mapping, priority=pl.priority, insertion=pl.insertion)
            res[h].append((ev.sim.makespan / opt, ev.feasible, dt))
            line.append(f"{h}={ev.sim.makespan / opt:.3f}")
        print("  ".join(line), flush=True)

    def q(xs: list[float], p: float) -> float:
        xs = sorted(xs)
        return xs[min(len(xs) - 1, int(p * (len(xs) - 1) + 0.5))]

    lines = [
        "# Heuristics vs exact optimum (Tier A v0, bus contention)",
        "",
        f"Generated by `scripts/bench_heuristics.py` on {date.today().isoformat()}: the first {len(recs)} optimally "
        "labelled instances of `data/labels/tier_a_v0_bus.synthetic.jsonl` (10–40 tasks). Optimum = CP-SAT label "
        "with shared-bus contention; heuristics evaluated by the simulator on the same model. **Synthetic instances.**",
        "",
        "| heuristic | makespan / optimum: median | p90 | max | optimal (≤ 0.1%) | deadline met | time median (s) | time max (s) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for h, xs in sorted(res.items(), key=lambda kv: statistics.median(x[0] for x in kv[1])):
        ratios = [x[0] for x in xs]
        lines.append(
            f"| {h} | {statistics.median(ratios):.3f} | {q(ratios, 0.9):.3f} | {max(ratios):.3f} | "
            f"{sum(x <= 1.001 for x in ratios)}/{len(xs)} | {sum(x[1] for x in xs)}/{len(xs)} | "
            f"{statistics.median(x[2] for x in xs):.3f} | {max(x[2] for x in xs):.2f} |")
    lines += ["", "Ratios below 1.000 can occur by at most ~0.15% (CP-SAT rounds durations up to whole µs)."]
    out = ROOT / "docs" / "benchmarks" / "heuristics_vs_optimum.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
